"""Write BOM.md: every printed part (structure.PARTS, with its plate), the owner's bought parts
(vitamins.items) and every screw, nut and T-nut (hardware.bolts). Generated, so the counts follow
the design; the gate fails when BOM.md is stale.

Run: python scripts/make_bom.py
"""
import os

import geom as G
import hardware as H
import params as P
import plates as PT
import structure as S
import vitamins as V

PATH = os.path.join(G.ROOT, "BOM.md")

HEAD = """# Bill of materials

Quantities for one machine, generated by `scripts/make_bom.py` from the design (do not edit by
hand). Nothing new to buy: the bought parts are the ones already on the machine (or its
drawer), and the fasteners are plain M3, M4 and M5 screws with 20-series T-nuts. Masses and
print times are in [`tracker.md`](tracker.md); where each part goes, in [`DESIGN.md`](DESIGN.md).
"""

VIT_NOTES = {
    "2020 / 2040 aluminium profile": "the frame as built: 4 posts, 2 top end bars (2040 on edge), 2 bottom end bars, "
                                     "2 long members. Measure it before printing (DESIGN.md, \"Measure first\")",
    "8 mm rod": f"{P.ROD_L:.0f} mm, {P.ROD_SPACING:.0f} mm apart (170-190 fit)",
    "SK8 rod support": "on the top end bars, as built",
    "SC8UU bearing block": "under the carriage plate, 4 x M4 x 10 each",
    "KP08 pillow block": "on the pivot bridge, in line, 70 mm apart",
    f"8 mm pivot shaft, {P.SHAFT_L:.0f} mm": "steel: an offcut of 8 mm rod or the plain shank of an M8 bolt "
                                              "(the KP08 set screws need steel)",
    "6 x 2.5 mm diametric magnet": "diametrically magnetised; most AS5600 boards come with one",
    "AS5600 magnetic encoder board": "corner holes 18-26 mm apart",
    "optional: 600 P/R optical encoder": f"instead of the AS5600: {P.LPD3806['d']:.0f} mm body, "
                                         f"{P.LPD3806['shaft']:.0f} mm shaft, M3 on a 28-32 mm circle",
    "NEMA 17 stepper": f"{P.NEMA17['torque']:.2f} N m holding or more (17HS4401 class), 1/16 microstepping",
    "mechanical endstop": f"lever switch on a {P.ENDSTOP['pcb'][0]:.0f} x {P.ENDSTOP['pcb'][1]:.0f} mm board, "
                          f"holes {P.ENDSTOP['hole_dx']:.0f} mm apart; wired normally closed",
    "stepper driver carrier (A4988 / DRV8825)": f"step/dir driver set to {P.DRIVE['i_set']:g} A, with its heatsink",
    "controller (Arduino Uno / Nano or ESP32)": "runs firmware/pendulum (FastAccelStepper: not an STM32)",
}

EXTRA = """
**Not drawn in the model** (small, from the drawer):

- 4 x M2.5 x 6 self-tapping screws (or M3) for the AS5600 board on its adapter.
- M3 screws or standoffs for the driver carrier and the controller on the tray (their slots take M3).
- Optical-encoder option: 3 x M3 x 6 into the encoder's face.
- CA glue (pulley flanges, the magnet in its cap), zip ties (sensor lead, tray), medium thread
  locker for the pulley's set screw (optional), a drop of grease or oil for the idler's sleeve.
- A 47-100 uF electrolytic capacitor across the driver's motor supply, if the carrier has none.
- Arduino IDE (or arduino-cli) with the FastAccelStepper library, to load `firmware/pendulum`.

**To confirm before printing:** the frame's size and the belt (`tracker.md`, "Before the first
print"), and that the drawer holds the {TNUTS} T-nuts, the M5 x 40 idler axle and an 8 mm x
{SHAFT} mm steel shaft.
"""


def _plate_of():
    out = {}
    for i, (plate, items) in enumerate(PT.PLATES.items(), start=1):
        for name, _ in items:
            out[name] = f"{i} `{plate}`"
    return out


def printed():
    plate = _plate_of()
    rows = ["| Part | Qty | Material | Plate | What it does |", "|---|---|---|---|---|"]
    for name, spec in S.PARTS.items():
        rows.append(f"| `{name}` | {len(spec['copies'])} | {spec['material'].upper()} | {plate.get(name, '-')} | "
                    f"{spec['role']} |")
    return rows


def bought():
    count, order = {}, []
    for _, _, _, _, label in V.items(belt=False):
        if label not in count:
            order.append(label)
        count[label] = count.get(label, 0) + 1
    lo, hi = P.BELT_LOOP_RANGE
    rows = ["| Item | Qty | Notes |", "|---|---|---|"]
    rows += [f"| {label} | {count[label]} | {VIT_NOTES.get(label, '')} |" for label in order]
    rows.append(f"| HTD 5M belt, {P.BELT['width']:.0f} mm wide | 1 | closed loop {lo:.0f}-{hi:.0f} mm (the tensioner's range), "
                f"or an open belt: cut {P.BELT_OPEN_CUT:.0f} mm, both ends in the clamp |")
    return rows


def fasteners():
    screws, nuts, tnuts, washers = {}, {}, [], 0
    for b in H.bolts():
        r = screws.setdefault((b["size"], b["length"]), dict(n=0, parts=[]))
        r["n"] += 1
        if b["part"] not in r["parts"]:
            r["parts"].append(b["part"])
        if b["nut"]:
            n = nuts.setdefault(b["size"], dict(n=0, parts=[]))
            n["n"] += 1
            if b["part"] not in n["parts"]:
                n["parts"].append(b["part"])
        if b["tnut"]:
            tnuts.append(b["part"])
        washers += "washer" in b["note"]
    rows = ["| Fastener | Qty | Where |", "|---|---|---|"]
    for (size, length), r in sorted(screws.items()):
        rows.append(f"| {size} x {length:.0f} | {r['n']} | {', '.join(f'`{p}`' for p in r['parts'])} |")
    for size, r in sorted(nuts.items()):
        rows.append(f"| {size} nut | {r['n']} | {', '.join(f'`{p}`' for p in r['parts'])} |")
    rows.append(f"| T-nut M5, 20-series | {len(tnuts)} | {', '.join(f'`{p}`' for p in dict.fromkeys(tnuts))} |")
    rows.append(f"| M5 washer | {washers} | under the `pivot_bridge` bolts' heads (slotted flanges) |")
    total = sum(r["n"] for r in screws.values()) + sum(r["n"] for r in nuts.values()) + len(tnuts)
    return rows, total, len(tnuts)


def render():
    n_parts = len(S.PARTS)
    n_copies = sum(len(s["copies"]) for s in S.PARTS.values())
    frows, total, n_tnuts = fasteners()
    out = [HEAD, f"## Printed parts\n\n{n_parts} part files, {n_copies} pieces, on {len(PT.PLATES)} plates "
                 f"(`coupler` only with the optical encoder).\n", *printed(),
           "\n## Bought parts (already on the machine)\n", *bought(),
           f"\n## Fasteners\n\n{total} pieces, each checked by the gate for length against what it clamps "
           f"(`scripts/hardware.py`, check `bolts`).\n", *frows,
           EXTRA.replace("{TNUTS}", str(n_tnuts)).replace("{SHAFT}", f"{P.SHAFT_L:.0f}")]
    return "\n".join(out)


def current():
    if not os.path.exists(PATH):
        return None
    with open(PATH, encoding="utf-8") as f:
        return f.read()


def main():
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print("wrote BOM.md")


if __name__ == "__main__":
    main()
